async function seedDatabase() {
  console.log("🌱 Starting Comprehensive FALCON Database Seed...");

  // 1. Ensure Seller User
  let seller = await User.findOne({ role: "seller" });
  if (!seller) {
    seller = await User.create({
      firstname: "FALCON",
      lastname: "Official",
      email: "official@falcondevices.com",
      mobile: "+919876543210",
      role: "seller",
      location: { type: "Point", coordinates: [77.5946, 12.9716] },
      address: {
        city: "Bengaluru",
        state: "Karnataka",
        pincode: "560001",
        full: "MG Road, Bengaluru, Karnataka",
      },
    });
    console.log("Created official seller user ✅");
  }

  const defaultLocation = {
    type: "Point",
    coordinates: [77.5946, 12.9716],
  };
  const defaultAddress = {
    city: "Bengaluru",
    state: "Karnataka",
    pincode: "560001",
    full: "FALCON Experience Hub, MG Road, Bengaluru",
  };

  // 2. Clear existing products to ensure clean, non-duplicate verified catalog
  await Product.deleteMany({});
  console.log("Cleared existing products.");

  // 3. Insert Mobiles
  const mobileDocs = mobileModels.map((m) => ({
    ...m,
    listedBy: seller._id,
    listedByRole: "seller",
    location: defaultLocation,
    address: defaultAddress,
    status: "available",
    quantity: 15,
  }));
  await Product.insertMany(mobileDocs);
  console.log(`✅ Seeded ${mobileDocs.length} Mobile Models!`);

  // 4. Insert Laptops
  const laptopDocs = laptopModels.map((l) => ({
    ...l,
    listedBy: seller._id,
    listedByRole: "seller",
    location: defaultLocation,
    address: defaultAddress,
    status: "available",
    quantity: 12,
  }));
  await Product.insertMany(laptopDocs);
  console.log(`✅ Seeded ${laptopDocs.length} Laptop Models!`);

  // 5. Seed DeviceCatalog for Sell/Trade-in feature
  await DeviceCatalog.deleteMany({});
  
  // Group all devices by brand and category for DeviceCatalog
  const catalogMap = {};
  [...mobileDocs, ...laptopDocs].forEach((dev) => {
    const key = `${dev.brand}_${dev.category}`;
    if (!catalogMap[key]) {
      catalogMap[key] = {
        brand: dev.brand,
        category: dev.category,
        models: [],
      };
    }
    const specsMap = new Map();
    if (dev.specs?.performance?.ram) specsMap.set("ram", dev.specs.performance.ram);
    if (dev.storage) specsMap.set("storage", dev.storage);
    if (dev.specs?.processor) specsMap.set("processor", dev.specs.processor);

    catalogMap[key].models.push({
      name: dev.title,
      image: dev.images[0],
      variants: [
        {
          specs: specsMap,
          basePrice: Math.round(dev.price * 0.75),
        },
      ],
      soldCount: Math.floor(Math.random() * 50) + 10,
    });
  });

  const catalogDocs = Object.values(catalogMap);
  await DeviceCatalog.insertMany(catalogDocs);
  console.log(`✅ Seeded DeviceCatalog for ${catalogDocs.length} brand-category groups!`);

  console.log("🎉 FALCON Seed Completed Successfully!");
  console.log(`Total Mobiles: ${mobileDocs.length}, Total Laptops: ${laptopDocs.length}, Total Products: ${mobileDocs.length + laptopDocs.length}`);
}

module.exports = seedDatabase;

if (require.main === module) {
  const connectToDB = require("../config/db");
  connectToDB()
    .then(async () => {
      await seedDatabase();
      process.exit(0);
    })
    .catch((err) => {
      console.error("Seed failed:", err);
      process.exit(1);
    });
}
